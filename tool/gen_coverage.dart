// Regenerates lib/src/coverage.g.dart from the bundled font files.
//
//   dart run tool/gen_coverage.dart
//
// test/coverage_test.dart fails when the generated table is stale.
import 'dart:io';

import 'cmap.dart';

/// Coverage key → font files. A family with several files (Nunito regular +
/// italic) gets the intersection, so "covered" holds for every style.
const kidCoverageSources = {
  'DynaPuff': ['DynaPuff-Variable.ttf'],
  'Baloo2': ['Baloo2-Variable.ttf'],
  'GrandstanderItalic': ['Grandstander-Italic-Variable.ttf'],
  'Nunito': ['Nunito-Variable.ttf', 'Nunito-Italic-Variable.ttf'],
};

/// Sorted code points → flat [start, end, start, end, …] inclusive ranges.
List<int> toRanges(Iterable<int> codePoints) {
  final sorted = codePoints.toList()..sort();
  final out = <int>[];
  for (final c in sorted) {
    if (out.isNotEmpty && out.last == c - 1) {
      out.last = c;
    } else {
      out
        ..add(c)
        ..add(c);
    }
  }
  return out;
}

Map<String, List<int>> computeCoverage(String fontsDir) => {
  for (final MapEntry(key: key, value: files) in kidCoverageSources.entries)
    key: toRanges(
      files.map((f) => readCmap(File('$fontsDir/$f').readAsBytesSync())).reduce((a, b) => a.intersection(b)),
    ),
};

String render(Map<String, List<int>> coverage) {
  final b = StringBuffer()
    ..writeln('// GENERATED by tool/gen_coverage.dart from fonts/*.ttf — do not edit.')
    ..writeln('// Flat inclusive code point ranges: [start, end, start, end, …].')
    ..writeln()
    ..writeln('const kidCoverageRanges = <String, List<int>>{');
  for (final MapEntry(:key, :value) in coverage.entries) {
    b.writeln("  '$key': [");
    for (var i = 0; i < value.length; i += 16) {
      b.writeln(
        '    ${value.sublist(i, i + 16 > value.length ? value.length : i + 16).map((c) => '0x${c.toRadixString(16).toUpperCase()}').join(', ')},',
      );
    }
    b.writeln('  ],');
  }
  b.writeln('};');
  return b.toString();
}

void main() {
  final out = File('lib/src/coverage.g.dart')..writeAsStringSync(render(computeCoverage('fonts')));
  stdout.writeln('wrote ${out.path}');
}
